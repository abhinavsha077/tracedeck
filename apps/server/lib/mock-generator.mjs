// Zero-dependency offline network mock generator (MSW & standalone fetch interceptor)
// Enables instant offline reproduction for frontend engineers

export function extractNetworkCalls(capture) {
  if (!capture || !Array.isArray(capture.events)) return [];
  return capture.events
    .filter(e => e.type === 'network')
    .map(e => {
      const data = e.data || {};
      const method = (e.method || data.method || 'GET').toUpperCase();
      const url = e.url || data.url || '';
      const status = Number(e.status ?? data.status ?? 200);
      let responseBody = e.responseBody ?? data.responseBody ?? null;
      let requestBody = e.requestBody ?? data.requestBody ?? null;

      return {
        method,
        url,
        status,
        requestBody,
        responseBody,
        headers: e.headers || data.headers || {}
      };
    })
    .filter(call => Boolean(call.url));
}

export function generateMswHandlers(capture) {
  const calls = extractNetworkCalls(capture);
  if (calls.length === 0) {
    return `// No network calls recorded in this capture\nimport { http } from 'msw';\n\nexport const handlers = [];\n`;
  }

  const seen = new Set();
  const handlers = [];

  for (const call of calls) {
    const key = `${call.method}:${call.url}`;
    if (seen.has(key)) continue;
    seen.add(key);

    let parsedBody;
    try {
      parsedBody = typeof call.responseBody === 'string' ? JSON.parse(call.responseBody) : call.responseBody;
    } catch {
      parsedBody = call.responseBody || {};
    }

    const formattedJson = JSON.stringify(parsedBody ?? {}, null, 2).split('\n').map((line, idx) => idx === 0 ? line : '    ' + line).join('\n');
    const methodLower = call.method.toLowerCase();
    const safeMethod = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'].includes(methodLower) ? methodLower : 'all';

    handlers.push(`  http.${safeMethod}('${call.url}', () => {\n    return HttpResponse.json(\n    ${formattedJson},\n    { status: ${call.status} }\n    );\n  })`);
  }

  return `/**
 * Mock Service Worker (MSW) Handlers
 * Generated by DevDesk for Capture: ${capture.id || 'unknown'} (${capture.title || 'Untitled'})
 */
import { http, HttpResponse } from 'msw';

export const handlers = [
${handlers.join(',\n\n')}
];
`;
}

export function generateFetchMock(capture) {
  const calls = extractNetworkCalls(capture);
  const jsonMap = {};

  for (const call of calls) {
    const key = `${call.method}:${call.url}`;
    let body = call.responseBody;
    try {
      if (typeof body === 'string') body = JSON.parse(body);
    } catch {}
    jsonMap[key] = {
      status: call.status,
      body: body ?? {}
    };
  }

  return `/**
 * Standalone Zero-Dependency Offline Mock Interceptor
 * Generated by DevDesk for Capture: ${capture.id || 'unknown'}
 */
(function installOfflineMocks() {
  const mocks = ${JSON.stringify(jsonMap, null, 2)};
  const origFetch = globalThis.fetch;

  globalThis.fetch = async function(input, init) {
    const url = typeof input === 'string' ? input : (input && input.url ? input.url : String(input));
    const method = ((init && init.method) || (input && input.method) || 'GET').toUpperCase();
    const key = method + ':' + url;

    if (mocks[key]) {
      const match = mocks[key];
      console.info('[DevDesk Mock]', method, url, '->', match.status);
      return new Response(JSON.stringify(match.body), {
        status: match.status,
        headers: { 'content-type': 'application/json' }
      });
    }

    if (origFetch) {
      return origFetch.apply(this, arguments);
    }
    return new Response(JSON.stringify({ error: 'Route not mocked and no native fetch available' }), { status: 404 });
  };

  console.log('[DevDesk] Offline network mock installed for ' + Object.keys(mocks).length + ' routes.');
})();
`;
}
